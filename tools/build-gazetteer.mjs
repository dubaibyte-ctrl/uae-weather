// Generates src/lib/places-data.js (importable by the Worker and tests) from the browser's public/data/places.json,
// so there is a single source of truth for coordinates. Run after build-places.mjs.
import fs from "node:fs";
const here = new URL("./", import.meta.url).pathname;
const db = JSON.parse(fs.readFileSync(here + "../public/data/places.json", "utf8"));
const places = db.places.map((p) => ({ id: p.id, en: p.en, ar: p.ar || "", em: p.em, reg: p.reg || "", lat: p.lat, lon: p.lon }));
const out = `// AUTO-GENERATED by tools/build-gazetteer.mjs from public/data/places.json. Do not edit by hand.\n` +
  `export const EMIRATES = ${JSON.stringify(db.emirates)};\n` +
  `export const PLACES = ${JSON.stringify(places)};\n`;
fs.writeFileSync(here + "../src/lib/places-data.js", out);
console.log("places-data.js:", places.length, "places,", places.filter((p) => p.ar).length, "with Arabic");
